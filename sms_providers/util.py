def _safe_int(value, default: int) -> int:
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def _safe_float(value, default: float) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _safe_bool(value, default: bool) -> bool:
    if value in (None, ""):
        return default
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() not in {"0", "false", "no", "off", "否"}

def parse_price_spec(spec) -> tuple[float, float, float]:
    """解析价格字符串或数值配置。
    返回 (min_price, max_price, exact_price)
    - 留空 / -1 / 0 -> (-1.0, -1.0, -1.0) 不限
    - "0.008" 或 "=0.008" -> (0.008, 0.008, 0.008) 锁定指定金额
    - "0.008-0.01" 或 "0.008~0.01" -> (0.008, 0.01, -1.0) 价格区间
    - ">=0.008" 或 ">0.008" -> (0.008, -1.0, -1.0) 最低金额限制
    - "<=0.25" 或 "<0.25" -> (-1.0, 0.25, -1.0) 最高金额限制
    """
    if spec is None or spec == "":
        return -1.0, -1.0, -1.0
    if isinstance(spec, (int, float)):
        val = float(spec)
        if val <= 0:
            return -1.0, -1.0, -1.0
        return val, val, val
    s = str(spec).strip()
    if not s or s.lower() in ("-1", "0", "不限", "none", "null"):
        return -1.0, -1.0, -1.0

    # 区间格式: 0.008-0.01 / 0.008~0.01 / 0.008..0.01 / 0.008,0.01
    for sep in ("..", "-", "~", ","):
        if sep in s:
            parts = s.split(sep, 1)
            try:
                min_p = float(parts[0].strip()) if parts[0].strip() else -1.0
            except ValueError:
                min_p = -1.0
            try:
                max_p = float(parts[1].strip()) if parts[1].strip() else -1.0
            except ValueError:
                max_p = -1.0
            exact_p = min_p if (min_p > 0 and min_p == max_p) else -1.0
            return min_p, max_p, exact_p

    # >= / >
    if s.startswith(">="):
        try:
            return float(s[2:].strip()), -1.0, -1.0
        except ValueError:
            return -1.0, -1.0, -1.0
    if s.startswith(">"):
        try:
            return float(s[1:].strip()), -1.0, -1.0
        except ValueError:
            return -1.0, -1.0, -1.0

    # <= / <
    if s.startswith("<="):
        try:
            return -1.0, float(s[2:].strip()), -1.0
        except ValueError:
            return -1.0, -1.0, -1.0
    if s.startswith("<"):
        try:
            return -1.0, float(s[1:].strip()), -1.0
        except ValueError:
            return -1.0, -1.0, -1.0

    # = / ==
    if s.startswith("=="):
        try:
            v = float(s[2:].strip())
            return v, v, v
        except ValueError:
            return -1.0, -1.0, -1.0
    if s.startswith("="):
        try:
            v = float(s[1:].strip())
            return v, v, v
        except ValueError:
            return -1.0, -1.0, -1.0

    # 单纯数值: 如 "0.008" 或 "0.01" —— 与网页点选一致：锁死该档位，不允许更便宜
    try:
        val = float(s)
        if val <= 0:
            return -1.0, -1.0, -1.0
        return val, val, val
    except ValueError:
        return -1.0, -1.0, -1.0
